import json
import os
import urllib.request
from pathlib import Path

USERNAME = "anirudhyadav0"
TOKEN = os.environ.get("GITHUB_TOKEN", "")

def get_json(url):
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.github+json",
            "Authorization": f"Bearer {TOKEN}",
            "X-GitHub-Api-Version": "2022-11-28"
        }
    )
    with urllib.request.urlopen(request, timeout=20) as response:
        return json.load(response)

def check_site(url):
    if not url or "YOUR_ACTUAL" in url:
        return "Not configured"

    try:
        request = urllib.request.Request(
            url,
            method="GET",
            headers={"User-Agent": "GitHub-Profile-Monitor"}
        )
        with urllib.request.urlopen(request, timeout=15) as response:
            return "Online" if response.status < 400 else "Check site"
    except Exception:
        return "Unavailable / check required"

config = json.loads(Path("projects.json").read_text())
demo_urls = config.get("demo_urls", {})

repos = []
for page in range(1, 6):
    batch = get_json(
        f"https://api.github.com/users/{USERNAME}/repos"
        f"?type=owner&sort=updated&per_page=100&page={page}"
    )
    repos.extend(batch)
    if len(batch) < 100:
        break

repos = [
    repo for repo in repos
    if not repo["fork"]
    and not repo["archived"]
    and repo["name"].lower() != USERNAME.lower()
]
repos.sort(key=lambda repo: repo["pushed_at"] or "", reverse=True)

lines = [
    "<!-- AUTO-PROJECTS:START -->",
    "<!-- This section is generated by GitHub Actions. -->",
    ""
]

for repo in repos:
    name = repo["name"]
    url = repo["html_url"]
    description = repo.get("description") or "No description added yet."
    description = description.replace("\n", " ").strip()
    lines.append(f"### [{name}]({url})")
    lines.append(description)
    lines.append("")

    demo = demo_urls.get(name)
    if demo:
        status = check_site(demo)
        lines.append(f"- **Live Demo:** [Open website]({demo})")
        lines.append(f"- **Last check:** {status}")
    else:
        lines.append("- **Live Demo:** Not configured")

    if repo.get("language"):
        lines.append(f"- **Main language:** {repo['language']}")

    lines.append(f"- **Updated:** {repo['updated_at'][:10]}")
    lines.append("")

lines.append("<!-- AUTO-PROJECTS:END -->")
generated = "\n".join(lines)

readme_path = Path("README.md")
readme = readme_path.read_text(encoding="utf-8")

start = "<!-- AUTO-PROJECTS:START -->"
end = "<!-- AUTO-PROJECTS:END -->"

if start not in readme or end not in readme:
    raise ValueError(
        "Add AUTO-PROJECTS START and END markers to README.md first."
    )

before, remainder = readme.split(start, 1)
_, after = remainder.split(end, 1)

readme_path.write_text(
    before + generated + after,
    encoding="utf-8"
)

print(f"Updated profile with {len(repos)} repositories.")
